print(1%3) # out: de la divicion que hagas devuelveme el resto. cuantas veces cabe el 3 en el 1 

print(2 ** 3) # out: 8 -> esto lo eleva a 3, es decir 2 elevado a 3

NUMERO = NUMERO + 2 # Aca podemos tambien remplazar el mismo valor numero y sumarle 2 
