# Como podriamos mostrar una doble comilla o comilla dentro de un String ?
# en python se utiliza el backslash antes de las comillas.
curso = "Ultimate \" Python \"   "
print(curso)  # out: Ultimate "Python

# \"
# \'
# \\
# \n

# \": comillas dobles dentro de un string con comillas dobles.
# "Hola \"mundo\""

# \': comillas simples dentro de un string con comillas simples.
# 'It\'s Python'

# \\: una barra invertida literal (\).
# "C:\\carpeta\\archivo.txt"

# \n: salto de línea.
# "Primera línea\nSegunda línea"
